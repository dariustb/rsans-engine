Element ansiLine(const std::string& line) {
    Elements runs;
    std::optional<ftxui::Color> foreground;
    std::optional<ftxui::Color> background;
    std::string current;

    const auto flush = [&] {
        if (current.empty()) {
            return;
        }
        Element run = text(current);
        if (foreground) {
            run = run | color(*foreground);
        }
        if (background) {
            run = run | bgcolor(*background);
        }
        runs.push_back(std::move(run));
        current.clear();
    };

    std::size_t i = 0;
    while (i < line.size()) {
        // An SGR sequence: ESC [ digits/semicolons m
        if (line[i] == '\033' && i + 1 < line.size() && line[i + 1] == '[') {
            const std::size_t end = line.find('m', i + 2);
            if (end != std::string::npos &&
                line.find_first_not_of("0123456789;", i + 2) == end) {
                flush();
                applyCodes(line.substr(i + 2, end - i - 2), foreground, background);
                i = end + 1;
                continue;
            }
        }
        current += line[i];
        ++i;
    }
    flush();
    return hbox(std::move(runs));
}

Element titleArt() {
    Elements rows;
    for (const char* line : titleLines) {
        rows.push_back(ansiLine(line));
    }
    return vbox(std::move(rows));
}
