std::optional<ftxui::Color> paletteColor(int index) {
    return ftxui::Color(static_cast<ftxui::Color::Palette16>(index));
}

// Applies one SGR parameter list ("0;94;44") to the current colors
void applyCodes(const std::string& codes, std::optional<ftxui::Color>& foreground,
                std::optional<ftxui::Color>& background) {
    std::size_t start = 0;
    while (start <= codes.size()) {
        const std::size_t end = std::min(codes.find(';', start), codes.size());
        const std::string part = codes.substr(start, end - start);
        const int code = part.empty() ? 0 : std::stoi(part);
        if (code == 0) {
            foreground.reset();
            background.reset();
        } else if (code >= 30 && code <= 37) {
            foreground = paletteColor(code - 30);
        } else if (code >= 90 && code <= 97) {
            foreground = paletteColor(code - 90 + 8);
        } else if (code >= 40 && code <= 47) {
            background = paletteColor(code - 40);
        } else if (code >= 100 && code <= 107) {
            background = paletteColor(code - 100 + 8);
        } else if (code == 39) {
            foreground.reset();
        } else if (code == 49) {
            background.reset();
        }
        start = end + 1;
    }
}

